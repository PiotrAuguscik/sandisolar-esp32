const ParameterSpec* find_parameter(RegisterTable table, std::uint16_t address) {
  for (const auto& parameter : kParameters)
    if (parameter.table == table && parameter.address == address) return &parameter;
  return nullptr;
}

Result<ParameterReading> decode_parameter(const ParameterSpec& parameter,
                                          const RegisterBlockView& block) {
  if (parameter.scale_denominator == 0) return {Error::InvalidArgument,{}};
  if (parameter.table != block.table) return {Error::FieldOutOfRange,{}};
  const auto raw = decode_register_value(block, parameter.address, parameter.encoding);
  if (!raw) return {raw.error,{}};
  return {Error::None,{raw.value,parameter.scale_numerator,parameter.scale_denominator,
      parameter.unit,parameter.meaning_evidence,parameter.encoding_evidence,
      parameter.scale_evidence,parameter.applicability}};
}

double proposed_value(const ParameterReading& reading) {
  return static_cast<double>(reading.raw.value) * reading.scale_numerator /
      reading.scale_denominator;
}

const char* evidence_name(Evidence evidence) {
  switch (evidence) {
    case Evidence::Unknown: return "unknown";
    case Evidence::ProtocolMap: return "protocol_map";
    case Evidence::Hypothesis: return "hypothesis";
    case Evidence::ConflictingSources: return "conflicting_sources";
  }
  return "unknown";
}

const char* applicability_name(Applicability applicability) {
  switch (applicability) {
    case Applicability::ModelDependent: return "model_dependent";
    case Applicability::NotSinglePhaseAccordingToMap: return "not_single_phase_according_to_map";
    case Applicability::SinglePhaseAccordingToMap: return "single_phase_according_to_map";
  }
  return "model_dependent";
}
